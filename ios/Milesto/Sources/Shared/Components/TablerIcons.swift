import SwiftUI

struct TablerIcons: View {
    private let unicode: String
    var size: CGFloat = 24
    var color: Color?

    init(_ icon: TablerIcon, size: CGFloat = 24, color: Color? = nil) {
        unicode = icon.rawValue
        self.size = size
        self.color = color
    }

    var body: some View {
        Text(unicode)
            .font(.custom("tabler-icons", size: size))
            .foregroundStyle(color ?? Color("TextSecondary"))
    }
}

struct TablerTabLabel: View {
    let icon: TablerIcon
    let title: String

    init(_ icon: TablerIcon, title: String) {
        self.icon = icon
        self.title = title
    }

    private var iconImage: Image {
        let renderer = ImageRenderer(
            content: Text(icon.rawValue)
                .font(.custom("tabler-icons", size: 24))
                .foregroundStyle(Color("TextPrimary"))
        )
        renderer.scale = UITraitCollection.current.displayScale
        if let uiImage = renderer.uiImage {
            return Image(uiImage: uiImage.withRenderingMode(.alwaysTemplate))
        }

        let fallbackRenderer = ImageRenderer(
            content: Text(TablerIcon.questionMark.rawValue)
                .font(.custom("tabler-icons", size: 24))
                .foregroundStyle(Color("TextPrimary"))
        )
        fallbackRenderer.scale = UITraitCollection.current.displayScale
        guard let fallbackImage = fallbackRenderer.uiImage else {
            return Image(uiImage: UIImage())
        }
        return Image(uiImage: fallbackImage.withRenderingMode(.alwaysTemplate))
    }

    var body: some View {
        Label {
            Text(title)
        } icon: {
            iconImage
        }
    }
}

extension TablerIcons {
    func size(_ size: CGFloat) -> TablerIcons {
        var copy = self
        copy.size = size
        return copy
    }

    func color(_ color: Color) -> TablerIcons {
        var copy = self
        copy.color = color
        return copy
    }
}

